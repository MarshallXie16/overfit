// Menu-flow smoke test. Usage: node tools/menus-e2e.mjs [baseUrl]
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:5173/';
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.addInitScript(() => { if (!sessionStorage.getItem('init')) { localStorage.clear(); localStorage.setItem('overfit.settings', JSON.stringify({ edgeScroll: false, master: 0 })); sessionStorage.setItem('init', '1'); } });
await page.goto(base, { waitUntil: 'load' });
await page.waitForSelector('.logo', { timeout: 20000 });
const ok = []; const check = (n, c, i = '') => { ok.push(c); console.log(`${c ? 'PASS' : 'FAIL'} ${n} ${i}`); };
check('title shows', await page.isVisible('text=CAMPAIGN'));
await page.screenshot({ path: 'output/m1-title.png' });
await page.click('[data-a=campaign]');
await page.waitForSelector('[data-m]');
const nm = await page.$$eval('[data-m]', (b) => b.map((x) => x.textContent.trim().slice(0, 40)));
check('mission list', nm.length >= 1, JSON.stringify(nm));
await page.screenshot({ path: 'output/m2-campaign.png' });
await page.click('[data-m]:not([disabled])');
await page.waitForSelector('[data-a=go]');
await page.screenshot({ path: 'output/m3-briefing.png' });
check('briefing pauses', await page.evaluate(() => window.overfit.session.world.paused));
await page.keyboard.press('Enter');
await page.waitForTimeout(3000);
const st = await page.evaluate(() => ({ m: window.overfit.session.world.settings.missionId, paused: window.overfit.session.world.paused, objs: window.overfit.session.world.objectives.length, t: window.overfit.session.world.time }));
check('mission running', !!st.m && !st.paused && st.t > 1, JSON.stringify(st));
await page.screenshot({ path: 'output/m4-mission.png' });
await page.keyboard.press('Escape');
await page.waitForSelector('[data-a=quit]');
await page.click('[data-a=quit]');
await page.waitForSelector('.logo');
check('quit to title', true);
await page.click('[data-a=endless]');
await page.waitForSelector('[data-a=daily]');
await page.screenshot({ path: 'output/m5-endless.png' });
await page.click('[data-a=daily]');
await page.waitForTimeout(1500);
const en = await page.evaluate(() => ({ mode: window.overfit.session.world.settings.mode, seed: window.overfit.session.world.settings.seed }));
check('daily endless starts', en.mode === 'endless', JSON.stringify(en));
// force a defeat and check the end screen + share card
await page.evaluate(() => { const w = window.overfit.session.world; for (const e of w.entities) if (e.kind === 'hq') e.hp = -1, w.kill(e); });
await page.waitForSelector('[data-a=share]', { timeout: 15000 }).catch(() => {});
await page.screenshot({ path: 'output/m6-end.png' });
check('end screen with share card', await page.isVisible('[data-a=share]'));
await page.click('[data-a=quit]');
await page.click('[data-a=settings]');
await page.waitForSelector('[data-s=music]');
check('settings opens', true);
// regression: briefing → deploy → Esc → Quit → Enter must not soft-lock the title (leaked Enter listener)
await page.click('[data-a=back]');
await page.waitForSelector('.logo');
await page.click('[data-a=campaign]');
await page.click('[data-m]:not([disabled])');
await page.waitForSelector('[data-a=go]');
await page.keyboard.press('Escape'); // ignored while the briefing is up
await page.waitForTimeout(150);
check('esc ignored during briefing', await page.isVisible('[data-a=go]'));
await page.keyboard.press('Enter');
await page.waitForTimeout(500);
await page.keyboard.press('Escape');
await page.waitForSelector('[data-a=quit]');
await page.click('[data-a=quit]');
await page.waitForSelector('.logo');
await page.keyboard.press('Enter');
await page.waitForTimeout(300);
check('title survives stray Enter', await page.isVisible('.logo'));
// regression: Esc toggles pause reliably several times; P is ignored while the menu is open
await page.click('[data-a=skirmish]');
await page.click('[data-a=go]');
await page.waitForTimeout(800);
let toggles = 0;
for (let i = 0; i < 3; i++) {
  await page.keyboard.press('Escape'); await page.waitForTimeout(120);
  const open = await page.isVisible('[data-a=resume]');
  await page.keyboard.press('p'); await page.waitForTimeout(60);
  const stillPaused = await page.evaluate(() => window.overfit.session.world.paused);
  await page.keyboard.press('Escape'); await page.waitForTimeout(120);
  const closed = !(await page.isVisible('[data-a=resume]'));
  const running = await page.evaluate(() => !window.overfit.session.world.paused);
  if (open && stillPaused && closed && running) toggles++;
}
check('esc pause toggles x3 and P blocked while open', toggles === 3, `${toggles}/3`);
console.log(`errors: ${errors.length}`); for (const e of errors.slice(0, 8)) console.log('  ERR', e);
await browser.close();
process.exit(ok.every(Boolean) && !errors.length ? 0 : 1);
